//! Request methods.
//!
//! * [`HostMethod`]: served by `tf-hostd`. The frontend calls them through the app core with
//!   a `hostId`; the app core forwards them as [`crate::host::ClientMsg::Req`].
//! * [`AppMethod`]: served by the app core itself (host profiles, settings, tunnels, …).
//!
//! The generated TypeScript `HostMethods` / `AppMethods` interfaces map method name →
//! `{ params; result }`.

use crate::app::{DiagReport, HostProfile, HostStatusEntry, Settings, TunnelInfo, WslDistro, AppCapabilities};
use crate::model::{ActivityEvent, Answer, HostHealth, HostState, SetupStatus, ThinkingLevel, UsageTotals};
use crate::session::{ChangedFile, HistoryPage, SessionSnapshot};
use crate::term::{ScrollDirection, Split, TermMode};
use crate::{Empty, Millis};

macro_rules! methods {
    ($enum:ident, $ts_name:literal, { $( $name:literal => $variant:ident ( $params:ty ) -> $result:ty ; )* }) => {
        /// Typed request (`{ "method": …, "params": … }`).
        #[derive(Debug, Clone, serde::Serialize, serde::Deserialize)]
        #[serde(tag = "method", content = "params")]
        pub enum $enum {
            $( #[serde(rename = $name)] $variant($params), )*
        }

        impl $enum {
            pub const NAMES: &'static [&'static str] = &[$($name),*];

            pub fn name(&self) -> &'static str {
                match self { $( Self::$variant(_) => $name, )* }
            }

            /// Parse a request from its method name and raw params.
            pub fn parse(method: &str, params: serde_json::Value) -> Result<Self, crate::ApiError> {
                if !Self::NAMES.contains(&method) {
                    return Err(crate::ApiError::new("unknown_method", format!("unknown method `{method}`")));
                }
                serde_json::from_value(serde_json::json!({ "method": method, "params": params }))
                    .map_err(|e| crate::ApiError::new("invalid_params", format!("{method}: {e}")))
            }

            /// TypeScript `interface <name> { "<method>": { params: P; result: R }; … }`.
            pub fn ts_interface(cfg: &ts_rs::Config) -> String {
                use ts_rs::TS;
                let mut imports = std::collections::BTreeSet::new();
                let mut body = String::new();
                $(
                    imports.insert(<$params as TS>::ident(cfg));
                    imports.insert(<$result as TS>::ident(cfg));
                    body.push_str(&format!(
                        "  {:?}: {{ params: {}; result: {} }};\n",
                        $name,
                        <$params as TS>::name(cfg),
                        <$result as TS>::name(cfg),
                    ));
                )*
                let mut out = String::from("// Generated by tf-proto (methods.rs). Do not edit.\n");
                for ident in imports {
                    out.push_str(&format!("import type {{ {ident} }} from \"./{ident}\";\n"));
                }
                out.push_str(&format!("\nexport interface {} {{\n{}}}\n", $ts_name, body));
                out
            }
        }
    };
}

