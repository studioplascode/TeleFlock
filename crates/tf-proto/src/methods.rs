#[cfg(test)]
mod tests {
    use super::*;

    /// Writes `HostMethods.ts`, `AppMethods.ts` and `index.ts` next to the ts-rs output.
    /// Run through `scripts/gen-proto-ts.sh`.
    #[test]
    fn export_bindings_method_maps() {
        let Ok(dir) = std::env::var("TS_RS_EXPORT_DIR") else { return };
        let cfg = ts_rs::Config::from_env();
        let dir = std::path::Path::new(&dir);
        std::fs::create_dir_all(dir).unwrap();
        std::fs::write(dir.join("HostMethods.ts"), HostMethod::ts_interface(&cfg)).unwrap();
        std::fs::write(dir.join("AppMethods.ts"), AppMethod::ts_interface(&cfg)).unwrap();
    }

    #[test]
    fn parse_roundtrip() {
        let req = HostMethod::parse("agent.prompt", serde_json::json!({
            "agentId": "term_1", "text": "hi", "images": [], "delivery": "followUp"
        }))
        .unwrap();
        assert_eq!(req.name(), "agent.prompt");
        let HostMethod::AgentPrompt(p) = req else { panic!() };
        assert_eq!(p.delivery, Delivery::FollowUp);
        assert_eq!(HostMethod::parse("nope", serde_json::Value::Null).unwrap_err().code, "unknown_method");
        assert_eq!(
            HostMethod::parse("agent.abort", serde_json::json!({})).unwrap_err().code,
            "invalid_params"
        );
    }
}
