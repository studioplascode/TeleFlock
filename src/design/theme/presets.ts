/**
 * Premade themes. Each is ordinary theme CSS (the same format as a custom theme) built from a
 * table of variables; whatever a theme leaves out keeps TeleFlock's default from tokens.css.
 * `presets.test.ts` checks every one for legibility (contrast of text on its surfaces).
 *
 * The sunset (needs you) keeps white text (`--color-on-sun`) in every theme but High contrast: its
 * own decorations are white, so its colours stay saturated enough to carry white text.
 */

import { THEME_VARS } from "./vars";

export interface ThemePreset {
  id: string;
  name: string;
  description: string;
  scheme: "light" | "dark";
  /** Theme CSS; "" for the default. */
  css: string;
}

/** `#rrggbb` + alpha → `rgb(r g b / a)`. */
function alpha(hex: string, a: number): string {
  const n = Number.parseInt(hex.slice(1), 16);
  return `rgb(${(n >> 16) & 255} ${(n >> 8) & 255} ${n & 255} / ${a})`;
}

const ORDER = new Map(THEME_VARS.map((v, i) => [v.name, i]));

function themeCss(name: string, scheme: "light" | "dark", vars: Record<string, string>): string {
  const lines = Object.entries(vars)
    .map(([k, value]) => [`--${k}`, value] as const)
    .sort(([a], [b]) => (ORDER.get(a) ?? 999) - (ORDER.get(b) ?? 999))
    .map(([k, value]) => `  ${k}: ${value};`);
  return `/* TeleFlock theme: ${name} */\n:root {\n  color-scheme: ${scheme};\n${lines.join("\n")}\n}\n`;
}

/** Glow shadows tinted with a theme's own colours (same shapes as the default's). */
function glows(c: { accent: string; pink: string; sun1: string; sun2: string; run: string; review: string; done: string; error: string }, k = 1): Record<string, string> {
  return {
    "shadow-glow-accent": `0 10px 28px -8px ${alpha(c.accent, 0.75 * k)}, 0 2px 10px -4px ${alpha(c.pink, 0.4 * k)}`,
    "shadow-glow-sun": `0 18px 50px -12px ${alpha(c.sun2, 0.6 * k)}, 0 6px 24px -8px ${alpha(c.sun1, 0.45 * k)}`,
    "shadow-glow-run": `0 10px 28px -8px ${alpha(c.run, 0.75 * k)}`,
    "shadow-glow-review": `0 8px 22px -8px ${alpha(c.review, 0.6 * k)}`,
    "shadow-glow-done": `0 8px 22px -8px ${alpha(c.done, 0.5 * k)}`,
    "shadow-glow-error": `0 10px 26px -8px ${alpha(c.error, 0.6 * k)}`,
  };
}

/** Lines, wells and depth for a dark theme: white hairlines, black shadows tinted by `shade`. */
function darkDepth(line: string, shade: string, well: string): Record<string, string> {
  return {
    "color-line": alpha(line, 0.07),
    "color-line-2": alpha(line, 0.11),
    "color-line-3": alpha(line, 0.19),
    "color-well": alpha(well, 0.55),
    "color-well-2": alpha(well, 0.72),
    "shadow-d1": `inset 0 1px 0 ${alpha(line, 0.05)}, 0 1px 2px ${alpha(shade, 0.5)}, 0 8px 18px -6px ${alpha(shade, 0.5)}`,
    "shadow-d2": `inset 0 1px 0 ${alpha(line, 0.06)}, 0 2px 4px ${alpha(shade, 0.35)}, 0 14px 30px -8px ${alpha(shade, 0.55)}, 0 34px 64px -24px ${alpha(shade, 0.6)}`,
    "shadow-d3": `inset 0 1px 0 ${alpha(line, 0.09)}, 0 4px 10px ${alpha(shade, 0.35)}, 0 26px 50px -10px ${alpha(shade, 0.65)}, 0 70px 120px -30px ${alpha(shade, 0.75)}`,
    "shadow-key": `inset 0 -2px 0 ${alpha(shade, 0.35)}, inset 0 0 0 1px ${alpha(line, 0.07)}`,
    "shadow-hairline": `inset 0 0 0 1px ${alpha(line, 0.07)}`,
  };
}

