#!/usr/bin/env bash
# Regenerates src/core/gen/*.ts from crates/tf-proto (the single source of truth for the wire protocol).
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
out="$root/src/core/gen"
rm -rf "$out"
mkdir -p "$out"
export TS_RS_EXPORT_DIR="$out" TS_RS_LARGE_INT=number
export CARGO_TARGET_DIR="${CARGO_TARGET_DIR:-$root/target/proto}"
cargo test -q -p tf-proto --manifest-path "$root/Cargo.toml" >/dev/null
{
  echo "// Generated by scripts/gen-proto-ts.sh. Do not edit."
  for f in "$out"/*.ts; do
    name="$(basename "$f" .ts)"
    [ "$name" = index ] && continue
    echo "export type * from \"./$name\";"
  done
} >"$out/index.ts"
echo "generated $(ls "$out" | wc -l) files in ${out#$root/}"
