#!/usr/bin/env bash
# Regenerates src/core/gen/*.ts from crates/tf-proto (the single source of truth for the wire protocol).
# Generates into a scratch dir and swaps it in only when tf-proto compiled and exported, so a failed
# run leaves the existing bindings untouched.
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
out="$root/src/core/gen"
mkdir -p "$root/target"
tmp="$(mktemp -d "$root/target/gen-ts.XXXXXX")"
trap 'rm -rf "$tmp"' EXIT
export TS_RS_EXPORT_DIR="$tmp" TS_RS_LARGE_INT=number
export CARGO_TARGET_DIR="${CARGO_TARGET_DIR:-$root/target/proto}"
cargo test -q -p tf-proto --manifest-path "$root/Cargo.toml" >/dev/null
{
  echo "// Generated by scripts/gen-proto-ts.sh. Do not edit."
  for f in "$tmp"/*.ts; do
    name="$(basename "$f" .ts)"
    [ "$name" = index ] && continue
    echo "export type * from \"./$name\";"
  done
} >"$tmp/index.ts"
# mktemp -d creates 0700; the bindings are ordinary source files.
chmod 755 "$tmp"
rm -rf "$out"
mv "$tmp" "$out"
trap - EXIT
echo "generated $(ls "$out" | wc -l) files in ${out#$root/}"
